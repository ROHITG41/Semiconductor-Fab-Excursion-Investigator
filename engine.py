"""engine.py - framework-free pipeline logic shared by the LangGraph app, the offline scripted run,
the tests and the scorer. The LLM may propose; this module's deterministic code decides verdicts,
validates numbers and attaches the hold advisory. Humans sign (Stage 2).
"""
from __future__ import annotations

from datetime import datetime, timezone
from typing import Optional

from config import DATA_DIR, MAX_AGENT_STEPS
from sandbox import scan_notes
from schemas import (EvidenceItem, FaultCode, HypothesisAssessment, InvestigationReport, RunResult,
                     ValidationResult)
from tools_core import SimBackend, TOOL_NAMES
from validator import validate_report

RUNTIME_ASSETS = ("UV_", "POLISH_", "RO_", "N2_PURIFIER", "CHEM_FILTER")


def execute_tool(backend: SimBackend, name: str, args: dict) -> dict:
    if name not in TOOL_NAMES:
        return {"error": f"unknown tool {name}"}
    try:
        return getattr(backend, name)(**args)
    except TypeError as e:
        return {"error": f"bad arguments for {name}: {e}"}


def add_evidence(evidence: list[EvidenceItem], tool: str, args: dict, output: dict) -> EvidenceItem:
    item = EvidenceItem(id=f"E{len(evidence) + 1}", tool=tool, args=args, output=output)
    evidence.append(item)
    return item


def run_ingress(backend: SimBackend) -> dict:
    return scan_notes(backend.notes).to_dict()


def run_triage(backend: SimBackend) -> dict:
    """Deterministic verdict for the alarming tag."""
    return backend.check_guardband_and_cal(backend.alarm["tag"])


def hold_advisory(verdict: str) -> str:
    if verdict == "FAIL":
        return ("ADVISORY (generated by code, not by the AI): potential wafer-lot hold for lots processed on the "
                "affected point of use. QA and process engineering decide.")
    if verdict == "INDETERMINATE":
        return ("ADVISORY (generated by code): verdict is INDETERMINATE. Verify the instrument and re-measure "
                "before any lot decision.")
    return "No hold advisory: deterministic verdict is PASS."


# ---------------- scripted tool policy (also used by the fake model) ----------------
def next_tool_calls(alarm_tag: str, backend_assets: dict, evidence: list[EvidenceItem]) -> list[tuple[str, dict]]:
    """Deterministic investigation plan. Returns the next round of tool calls, [] when done."""
    done = {(e.tool, tuple(sorted(e.args.items()))) for e in evidence}
    tools_done = {e.tool for e in evidence}
    if not evidence:
        return [("check_guardband_and_cal", {"tag": alarm_tag}),
                ("query_sensor_window", {"tag": alarm_tag, "minutes_back": 120}),
                ("compute_rate_of_change", {"tag": alarm_tag, "minutes_back": 120})]
    if "trace_upstream_loop" not in tools_done:
        return [("trace_upstream_loop", {"asset_id": backend_assets["alarm_asset"]})]
    if "get_recent_work_orders" not in tools_done:
        trace = next(e for e in evidence if e.tool == "trace_upstream_loop").output
        ups = [u["asset_id"] for u in trace.get("upstream", [])]
        calls: list[tuple[str, dict]] = [("get_recent_work_orders", {"asset_id": "", "hours": 72})]
        for a in ups:
            if a.startswith(RUNTIME_ASSETS):
                calls.append(("get_resin_and_lamp_runtime", {"asset_id": a}))
        for t in backend_assets["upstream_tags"](ups):
            calls.append(("query_sensor_window", {"tag": t, "minutes_back": 120}))
        return [c for c in calls if (c[0], tuple(sorted(c[1].items()))) not in done][:10]
    if "search_knowledge_base" not in tools_done:
        return [("search_knowledge_base", {"query": _kb_query(backend_assets["kb_query"], evidence), "k": 3}),
                ("find_similar_past_cases", {"k": 3})]
    return []


def _kb_query(base: str, evidence: list[EvidenceItem]) -> str:
    """Scripted stand-in for what a real agent does: write the search query from what it has found so far."""
    words = [base]
    for ev in evidence:
        o = ev.output
        if ev.tool == "check_guardband_and_cal" and not o.get("calibration_valid", True):
            words.append("analyzer calibration overdue drift")
        if ev.tool == "get_resin_and_lamp_runtime" and "error" not in o and o.get("percent_of_rated_life", 0) >= 95:
            words.append(f"{o['kind']} near or beyond rated life")
        if ev.tool == "get_recent_work_orders":
            for w in o.get("work_orders", []):
                if w["asset"].startswith("VALVE") and w["hours_ago"] <= 4:
                    words.append("valve work air ingress dissolved oxygen")
    return " ".join(words)


def rules_diagnose(evidence: list[EvidenceItem], triage: dict) -> FaultCode:
    """Transparent rule-of-thumb diagnosis from evidence. Used by the offline scripted run and the fake
    model; it is also the natural 'no-agent' baseline for Stage 3."""
    runtimes = {e.output["asset_id"]: e.output for e in evidence
                if e.tool == "get_resin_and_lamp_runtime" and "error" not in e.output}
    wos = next((e.output["work_orders"] for e in evidence if e.tool == "get_recent_work_orders"), [])
    param = triage.get("parameter", "")
    pct = lambda prefix: max([r["percent_of_rated_life"] for a, r in runtimes.items() if a.startswith(prefix)] or [0])
    if not triage.get("calibration_valid", True):
        return FaultCode.SENSOR_DRIFT
    if "Dissolved oxygen" in param and any(w["asset"].startswith("VALVE") and w["hours_ago"] <= 4 for w in wos):
        return FaultCode.VALVE_DIAPHRAGM_LEAK
    if param.startswith("AMC") and pct("CHEM_FILTER") >= 95:
        return FaultCode.AMC_FILTER_BREAKTHROUGH
    if "N2 moisture" in param and pct("N2_PURIFIER") >= 95:
        return FaultCode.N2_PURIFIER_SATURATION
    if param.startswith("TOC") and pct("UV_") >= 100:
        return FaultCode.UV_LAMP_DECAY
    if param.startswith("Resistivity"):
        if pct("RO_") >= 100:
            return FaultCode.RO_MEMBRANE_DEGRADATION
        if pct("POLISH_") >= 100:
            return FaultCode.RESIN_EXHAUSTION
    return FaultCode.NO_CONFIRMED_EXCURSION


def build_scripted_report(evidence: list[EvidenceItem], triage: dict) -> InvestigationReport:
    code = rules_diagnose(evidence, triage)
    ev = lambda tool: [e.id for e in evidence if e.tool == tool]
    rt = [e for e in evidence if e.tool == "get_resin_and_lamp_runtime" and "error" not in e.output]
    key = {FaultCode.UV_LAMP_DECAY: "UV_", FaultCode.RESIN_EXHAUSTION: "POLISH_",
           FaultCode.RO_MEMBRANE_DEGRADATION: "RO_", FaultCode.N2_PURIFIER_SATURATION: "N2_PURIFIER",
           FaultCode.AMC_FILTER_BREAKTHROUGH: "CHEM_FILTER"}.get(code)
    support = ev("check_guardband_and_cal")
    detail = ""
    if key:
        hit = next((e for e in rt if e.output["asset_id"].startswith(key) and e.output["percent_of_rated_life"] >= 95), None)
        if hit:
            support = support + [hit.id]
            o = hit.output
            detail = (f" {o['asset_id']} ({o['kind']}) has run {o['hours']} h against a rated {o['rated_hours']} h "
                      f"({o['percent_of_rated_life']} percent of rated life).")
    if code == FaultCode.VALVE_DIAPHRAGM_LEAK:
        support += ev("get_recent_work_orders")
        detail = " A valve diaphragm work order was closed shortly before the alarm on an asset upstream of the point of use."
    if code == FaultCode.SENSOR_DRIFT:
        detail = f" {triage['calibration_note'].capitalize()}, so the reading cannot be trusted."
    kw = {FaultCode.UV_LAMP_DECAY: "uv", FaultCode.RESIN_EXHAUSTION: "resin", FaultCode.RO_MEMBRANE_DEGRADATION: "ro membrane",
          FaultCode.N2_PURIFIER_SATURATION: "purifier", FaultCode.AMC_FILTER_BREAKTHROUGH: "chemical filter",
          FaultCode.VALVE_DIAPHRAGM_LEAK: "valve", FaultCode.SENSOR_DRIFT: "calibration"}.get(code)
    # scripted demo only: cite a retrieved chunk only when its text actually discusses the finding
    kb_ids = [r["chunk_id"] for e in evidence if e.tool == "search_knowledge_base" for r in e.output.get("results", [])
              if kw and kw in r["text"].lower()][:2]
    narrative = (f"{triage['parameter']} on {triage['tag']} reads {triage['measured']} {triage['unit']} against a limit of "
                 f"{triage['limit']} {triage['unit']} (deterministic verdict {triage['verdict']}).{detail} "
                 f"Most likely cause: {code.value.replace('_', ' ').lower()}. This is an unofficial draft for human review.")
    hyps = [HypothesisAssessment(code=code, status="supported" if code != FaultCode.NO_CONFIRMED_EXCURSION else "unresolved",
                                 evidence_ids=support)]
    return InvestigationReport(root_cause_code=code, confidence="medium", hypotheses=hyps,
                               supporting_evidence_ids=support, knowledge_base_citations=kb_ids, narrative=narrative,
                               recommended_actions=["Have a qualified engineer review the evidence before any action."])


# ---------------- result assembly ----------------
def run_metrics_text(run) -> str:
    """One line of operating metrics, computed from the run record (monitoring)."""
    errs = sum(1 for e in run.evidence if "error" in e.output)
    t = f"{run.elapsed_s:.1f} s" if run.elapsed_s is not None else "not recorded"
    return (f"Run metrics: {len(run.evidence)} tool calls, {errs} tool error{'s' if errs != 1 else ''}, "
            f"{run.tool_rounds} agent rounds, elapsed {t}.")


def split_errors(evidence: list[EvidenceItem]) -> tuple[list[str], list[str]]:
    """(unrecovered, recovered) tool-error evidence ids. An error is 'recovered' when the SAME tool was
    called again later and succeeded (typically: wrong asset id, then corrected)."""
    unrecovered, recovered = [], []
    for i, x in enumerate(evidence):
        if "error" not in x.output:
            continue
        later_ok = any(y.tool == x.tool and "error" not in y.output for y in evidence[i + 1:])
        (recovered if later_ok else unrecovered).append(x.id)
    return unrecovered, recovered


def evidence_quality_notes(evidence: list[EvidenceItem]) -> list[str]:
    """Informational notes (no acknowledgement needed): tool errors the agent corrected itself."""
    _, rec = split_errors(evidence)
    notes = []
    if rec:
        notes.append(f"{len(rec)} tool call(s) returned an error that was corrected by a later successful call of the same tool ({', '.join(rec)}).")
    trace = next((x for x in evidence if x.tool == "trace_upstream_loop" and "error" not in x.output), None)
    if trace is not None:
        up_tags = {t for u in trace.output.get("upstream", []) if isinstance(u, dict) for t in u.get("sensor_tags", [])}
        looked = {x.args.get("tag") for x in evidence
                  if x.tool in ("query_sensor_window", "compute_rate_of_change") and "error" not in x.output}
        if up_tags and not (up_tags & looked):
            notes.append("No upstream sensor trend was read: the upstream trace found sensors, but only equipment records were "
                         "checked. Consider reading upstream sensor trends before relying on this conclusion.")
    return notes


def evidence_quality(evidence: list[EvidenceItem]) -> list[str]:
    """Code-computed warnings about how good the investigation was. Shown to the human before sign-off."""
    flags = []
    errs, _ = split_errors(evidence)
    if errs:
        flags.append(f"{len(errs)} of {len(evidence)} tool calls returned errors that were not corrected ({', '.join(errs)}).")
    ok = lambda tool: any(x.tool == tool and "error" not in x.output for x in evidence)
    if not ok("trace_upstream_loop"):
        flags.append("No upstream trace succeeded: upstream assets were not examined.")
    if not ok("get_resin_and_lamp_runtime"):
        flags.append("No runtime-versus-rated-life check succeeded.")
    if not ok("get_recent_work_orders"):
        flags.append("Recent work orders were not successfully checked.")
    if not ok("compute_rate_of_change") and not ok("query_sensor_window"):
        flags.append("The alarming sensor's trend was not examined.")
    return flags


def assemble(backend: SimBackend, mode: str, models: dict, notes_scan: dict, triage: dict,
             evidence: list[EvidenceItem], report: Optional[InvestigationReport], rounds: int,
             validation: Optional[ValidationResult] = None) -> RunResult:
    if validation is None:
        validation = (validate_report(report, evidence, triage, backend.alarm) if report
                      else ValidationResult(ok=False, violations=["no report produced"]))
    flags = evidence_quality(evidence)
    if rounds > MAX_AGENT_STEPS:
        flags.append(f"The investigation hit the step limit ({MAX_AGENT_STEPS} tool rounds); the agent's last tool request was not run, "
                     "so some checks may be missing.")
        rounds = MAX_AGENT_STEPS      # report executed rounds, not the cut-off request
    status = "AWAITING_HUMAN_REVIEW" if validation.ok else "FLAGGED_VALIDATION_FAILED"
    return RunResult(scenario_id=backend.scenario_id, mode=mode, models=models, alarm=backend.alarm,
                     notes_scan=notes_scan, triage=triage, evidence=evidence, report=report,
                     validation=validation, hold_advisory=hold_advisory(triage.get("verdict", "INDETERMINATE")),
                     status=status, recorded_at=datetime.now(timezone.utc).isoformat(timespec="seconds"),
                     tool_rounds=rounds, quality_flags=flags,
                     quality_notes=evidence_quality_notes(evidence))


def backend_assets(backend: SimBackend) -> dict:
    spec = backend.sensors[backend.alarm["tag"]]
    return {"alarm_asset": spec.asset_id,
            "kb_query": f"{spec.parameter} excursion causes and corrective action",
            "upstream_tags": lambda assets: [t for a in assets for t in backend._tags_on(a)][:4]}


def run_scripted_offline(scenario_id: str, data_dir=DATA_DIR, notes_override=None) -> RunResult:
    """Full pipeline with NO AI model: scripted tool plan + rules diagnosis. Wiring/UI demo only."""
    b = SimBackend(scenario_id, data_dir, notes_override=notes_override)
    scan = run_ingress(b)
    triage = run_triage(b)
    evidence: list[EvidenceItem] = []
    assets = backend_assets(b)
    rounds = 0
    while rounds < MAX_AGENT_STEPS:
        calls = next_tool_calls(b.alarm["tag"], assets, evidence)
        if not calls:
            break
        rounds += 1
        for name, args in calls:
            add_evidence(evidence, name, args, execute_tool(b, name, args))
    report = build_scripted_report(evidence, triage)
    return assemble(b, "scripted-offline", {"model": "none (rules, no AI)"}, scan, triage, evidence, report, rounds)
