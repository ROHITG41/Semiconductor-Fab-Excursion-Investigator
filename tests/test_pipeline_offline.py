import json

import pytest

from config import DATA_DIR
from engine import run_scripted_offline

ALL_GOLD = json.loads((DATA_DIR / "golden_excursions.json").read_text())["scenarios"]
GOLD = [g for g in ALL_GOLD if g.get("tier", "core") == "core"]   # hard-tier scenarios are covered in test_hard_scenarios.py


@pytest.mark.parametrize("g", GOLD, ids=lambda g: g["scenario_id"])
def test_scripted_pipeline(g):
    """WIRING check only: the rules and the simulator were written together, so a pass here is not an accuracy claim."""
    r = run_scripted_offline(g["scenario_id"])
    assert r.validation.ok, r.validation.violations
    assert r.status == "AWAITING_HUMAN_REVIEW" and r.mode == "scripted-offline"
    assert r.triage["verdict"] == g["expected_verdict"]
    assert r.notes_scan["blocked"] == g["notes_contain_injection"]
    assert r.report.root_cause_code.value == g["expected_root_cause"]
    assert r.tool_rounds <= 8 and len(r.evidence) >= 6


def test_injection_text_never_reaches_model_input():
    r = run_scripted_offline("S07")
    assert r.notes_scan["blocked"] and "ignore previous" not in r.notes_scan["for_llm"].lower()


def test_hold_advisory_is_code_generated():
    assert "generated by code" in run_scripted_offline("S01").hold_advisory


@pytest.mark.parametrize("g", GOLD, ids=lambda g: g["scenario_id"])
def test_no_tool_call_returned_an_error(g):
    """A tool error hidden inside evidence must never pass silently."""
    r = run_scripted_offline(g["scenario_id"])
    assert [e.id for e in r.evidence if "error" in e.output] == []
    assert {"search_knowledge_base", "find_similar_past_cases"} <= {e.tool for e in r.evidence}


def test_scripted_citations_are_relevant_to_the_finding():
    r = run_scripted_offline("S07")           # UV lamp case must not cite the valve / dissolved-oxygen chunk
    assert "UPW-06" not in r.report.knowledge_base_citations
    assert all(c in {"UPW-01", "UPW-02", "UPW-05", "UPW-03", "UPW-04"} for c in r.report.knowledge_base_citations)
